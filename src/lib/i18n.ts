/** Nome da classe no idioma escolhido. */
export function className(lang: Lang, cls: string): string {
  if (lang === "en") return cls;
  const names: Record<string, string> = {
    "Damage Dealer": "Causador de Dano",
    Tank: "Tanque",
    Marksman: "Atirador de Elite",
    Artillery: "Artilharia",
    Controller: "Controlador",
    Assassin: "Assassino",
    Support: "Suporte",
  };
  return names[cls] ?? cls;
}

/** Nome do modo de jogo no idioma escolhido. */
export function modeName(lang: Lang, mode: string): string {
  if (lang === "en") return mode;
  const names: Record<string, string> = {
    "Gem Grab": "Pique-Gema",
    "Brawl Ball": "Futebrawl",
    Heist: "Roubo",
    "Hot Zone": "Zona Estratégica",
    Bounty: "Caça-Estrelas",
    Knockout: "Nocaute",
  };
  return names[mode] ?? mode;
}
